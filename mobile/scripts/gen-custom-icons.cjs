/**
 * One-shot generator: extracts icon path data from the installed
 * lucide-react-native package (ISC license) for icons that have NO Heroicons
 * equivalent, and emits src/icons/custom.tsx — plain react-native-svg
 * components with a lucide-compatible props API (size / color / strokeWidth).
 *
 * NOTE: lucide-react-native was removed from dependencies after the Heroicons
 * migration. To re-run this script, temporarily install it first:
 *   npm i -D lucide-react-native && node scripts/gen-custom-icons.cjs && npm rm lucide-react-native
 *
 * Run: node scripts/gen-custom-icons.cjs
 */
const fs = require("fs");
const path = require("path");

// Icons used in the app that have no reasonable Heroicons v2 equivalent.
const WANTED = [
    "Activity",
    "AlarmClock",
    "CalendarOff",
    "CalendarPlus",
    "CalendarRange",
    "CalendarX",
    "CheckCheck",
    "CheckSquare",
    "Circle",
    "CircleDot",
    "Coffee",
    "Crop",
    "Crown",
    "Disc",
    "GitBranch",
    "GitMerge",
    "Handshake",
    "Keyboard",
    "ListChecks",
    "MicOff",
    "Palmtree",
    "Pin",
    "Save",
    "ScanFace",
    "Shapes",
    "Shield",
    "SmilePlus",
    "Sprout",
    "StickyNote",
    "SwitchCamera",
    "Target",
    "Thermometer",
    "Timer",
    "ToggleLeft",
    "ToggleRight",
    "UserCheck",
    "UserCog",
    "Workflow",
];

const distDir = path.join(
    __dirname,
    "..",
    "node_modules",
    "lucide-react-native",
    "dist",
    "esm",
);

// Build export-name -> icon file map from the package barrel.
const barrel = fs.readFileSync(
    path.join(distDir, "lucide-react-native.mjs"),
    "utf8",
);
const nameToFile = new Map();
const lineRe = /export\s*\{([^}]+)\}\s*from\s*['"](.+?)['"]/g;
let m;
while ((m = lineRe.exec(barrel))) {
    const file = m[2];
    const nameRe = /default\s+as\s+([A-Za-z0-9_]+)/g;
    let n;
    while ((n = nameRe.exec(m[1]))) {
        nameToFile.set(n[1], file);
    }
}

function extractNodes(src) {
    // Find `const __iconNode = [ ... ];` OR the array inside createLucideIcon(...)
    let arrText = null;
    const iconNode = src.match(/__iconNode\s*=\s*(\[[\s\S]*?\]);/);
    if (iconNode) arrText = iconNode[1];
    if (!arrText) {
        const call = src.match(/createLucideIcon\(\s*["'][^"']+["']\s*,\s*(\[[\s\S]*?\])\s*\)/);
        if (call) arrText = call[1];
    }
    if (!arrText) return null;
    // Evaluate the JS array literal (unquoted keys) safely-enough for a build script.
    // eslint-disable-next-line no-new-func
    return new Function(`return ${arrText};`)();
}

const missing = [];
const icons = [];
for (const name of WANTED) {
    const rel = nameToFile.get(name);
    if (!rel) {
        missing.push(name);
        continue;
    }
    const file = path.resolve(distDir, rel);
    const src = fs.readFileSync(file, "utf8");
    const nodes = extractNodes(src);
    if (!nodes) {
        missing.push(name + " (parse failed)");
        continue;
    }
    // Strip the react "key" attr; keep everything else.
    const clean = nodes.map(([tag, attrs]) => {
        const { key, ...rest } = attrs || {};
        return [tag, rest];
    });
    icons.push({ name, nodes: clean });
}

if (missing.length) {
    console.error("MISSING:", missing.join(", "));
    process.exit(1);
}

// Alias every react-native-svg primitive with an Svg prefix so generated icon
// exports (e.g. `Circle`) can't collide with the primitives.
const TAG_MAP = {
    path: "SvgPath",
    circle: "SvgCircle",
    rect: "SvgRect",
    line: "SvgLine",
    polyline: "SvgPolyline",
    polygon: "SvgPolygon",
    ellipse: "SvgEllipse",
};
const IMPORT_NAME = {
    SvgPath: "Path",
    SvgCircle: "Circle",
    SvgRect: "Rect",
    SvgLine: "Line",
    SvgPolyline: "Polyline",
    SvgPolygon: "Polygon",
    SvgEllipse: "Ellipse",
};

const usedTags = new Set();
for (const { nodes } of icons) {
    for (const [tag] of nodes) {
        if (!TAG_MAP[tag]) {
            console.error("Unknown SVG tag:", tag);
            process.exit(1);
        }
        usedTags.add(TAG_MAP[tag]);
    }
}

function attrsToJsx(attrs) {
    return Object.entries(attrs)
        .map(([k, v]) => `${k}=${JSON.stringify(String(v))}`)
        .join(" ");
}

let out = `/**
 * AUTO-GENERATED by scripts/gen-custom-icons.cjs — do not edit by hand.
 *
 * Custom stroke icons (path data from Lucide, ISC license) for glyphs that
 * have no Heroicons v2 equivalent. Rendered with the same props API as the
 * Heroicons components re-exported from ./index so call-sites can't tell the
 * difference: \`size\`, \`color\` (via currentColor), \`strokeWidth\`, \`fill\`,
 * \`style\`, plus any other react-native-svg prop.
 */
import type { ReactNode } from "react";
import Svg, { ${[...usedTags]
        .sort()
        .map((t) => `${IMPORT_NAME[t]} as ${t}`)
        .join(", ")} } from "react-native-svg";
import type { NumberProp, SvgProps } from "react-native-svg";

export interface IconProps extends SvgProps {
  size?: NumberProp;
}

const makeIcon =
  (children: ReactNode) =>
  ({ size = 24, ...props }: IconProps) => (
    <Svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      {...props}
    >
      {children}
    </Svg>
  );

`;

for (const { name, nodes } of icons) {
    const children = nodes
        .map(([tag, attrs]) => `    <${TAG_MAP[tag]} ${attrsToJsx(attrs)} />`)
        .join("\n");
    out += `export const ${name} = makeIcon(\n  <>\n${children}\n  </>,\n);\n\n`;
}

const outFile = path.join(__dirname, "..", "src", "icons", "custom.tsx");
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, out);
console.log(`Wrote ${icons.length} icons to ${outFile}`);