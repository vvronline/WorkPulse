// ── MessagingStyle thread store ────────────────────────────────────────────
// Signal accumulates the recent unread lines for a conversation and renders
// them as a single expandable MessagingStyle notification. The headless FCM
// task has no React/zustand state, so we persist the running history in MMKV
// (which works in the background) keyed by conversation. Capped to the last few
// lines (Signal shows ~7) with a TTL so stale threads don't grow unbounded.
const THREAD_STORE_PREFIX = "wp-msg-thread:";
const THREAD_MAX_MESSAGES = 7;
const THREAD_TTL_MS = 24 * 60 * 60 * 1000; // 1 day

export interface ThreadMessage {
  text: string;
  senderName: string;
  /** epoch ms */
  timestamp: number;
}

function threadStoreKey(conversationId: string): string {
  return `${THREAD_STORE_PREFIX}${conversationId}`;
}

/**
 * Append a freshly-received message to the conversation's persisted history and
 * return the capped, chronologically-ordered list to render in MessagingStyle.
 * Best-effort: any storage failure falls back to just the new message so the
 * notification still shows something.
 */
function appendThreadMessage(
  conversationId: string,
  message: ThreadMessage,
): ThreadMessage[] {
  const key = threadStoreKey(conversationId);
  let existing: ThreadMessage[] = [];
  try {
    const raw = storage.getString(key);
    if (raw) {
      const parsed = JSON.parse(raw) as ThreadMessage[];
      if (Array.isArray(parsed)) existing = parsed;
    }
  } catch {
    // corrupt/missing — start fresh
  }

  const now = Date.now();
  const merged = [...existing, message]
    // Drop anything older than the TTL so a long-dormant thread doesn't
    // resurface stale lines when a new message finally arrives.
    .filter(
      (m) =>
        m &&
        typeof m.timestamp === "number" &&
        now - m.timestamp < THREAD_TTL_MS,
    )
    .sort((a, b) => a.timestamp - b.timestamp)
    .slice(-THREAD_MAX_MESSAGES);

  try {
    storage.set(key, JSON.stringify(merged));
  } catch {
    // best-effort
  }
  return merged.length ? merged : [message];
}

/** Clears a conversation's accumulated notification history (read/opened). */
function clearThread(conversationId: string): void {
  try {
    storage.remove(threadStoreKey(conversationId));
  } catch {
    // best-effort
  }
}

// ── Active-conversation registry (group-summary bookkeeping) ────────────────
// Signal-Android renders ONE status-bar SUMMARY entry above the per-conversation
// children, with an InboxStyle that lists a line per active chat plus a running
// total ("5 messages from 3 chats"). To build/refresh that summary the headless
// FCM task must know WHICH conversations currently have an outstanding
// notification — but it has no React/zustand state and the MMKV wrapper only
// exposes get/set/remove (no key enumeration). We therefore keep a single JSON
// blob mapping conversationId → its latest line + unread count, updated on every
// post and pruned on read/open. Same 1-day TTL as the thread store so a stale
// entry can never resurrect a dead summary.
const ACTIVE_CONVERSATIONS_KEY = "wp-msg-active-convos";

interface ActiveConversation {
  /** Display title for the InboxStyle line (sender / group name). */
  title: string;
  /** Latest message body (for the InboxStyle line). */
  latestBody: string;
  /** Number of unread messages accumulated for this conversation. */
  count: number;
  /** epoch ms of the latest message — used for ordering + TTL prune. */
  timestamp: number;
}

type ActiveConversationMap = Record<string, ActiveConversation>;

function readActiveConversations(): ActiveConversationMap {
  try {
    const raw = storage.getString(ACTIVE_CONVERSATIONS_KEY);
    if (!raw) return {};
    const parsed = JSON.parse(raw) as ActiveConversationMap;
    if (!parsed || typeof parsed !== "object") return {};
    // Prune TTL-expired entries so the summary never lists a long-dead thread.
    const now = Date.now();
    const pruned: ActiveConversationMap = {};
    for (const [key, value] of Object.entries(parsed)) {
      if (
        value &&
        typeof value.timestamp === "number" &&
        now - value.timestamp < THREAD_TTL_MS
      ) {
        pruned[key] = value;
      }
    }
    return pruned;
  } catch {
    return {};
  }
}

function writeActiveConversations(map: ActiveConversationMap): void {
  try {
    if (Object.keys(map).length === 0) {
      storage.remove(ACTIVE_CONVERSATIONS_KEY);
    } else {
      storage.set(ACTIVE_CONVERSATIONS_KEY, JSON.stringify(map));
    }
  } catch {
    // best-effort
  }
}

/**
 * Record (or update) a conversation in the active-summary registry. Increments
 * the per-conversation unread count so the summary can show "N messages".
 * Returns the resulting map so the caller can decide whether to post a summary.
 */
function recordActiveConversation(
  conversationId: string,
  info: { title: string; latestBody: string },
): ActiveConversationMap {
  const map = readActiveConversations();
  const existing = map[conversationId];
  map[conversationId] = {
    title: info.title,
    latestBody: info.latestBody,
    count: (existing?.count ?? 0) + 1,
    timestamp: Date.now(),
  };
  writeActiveConversations(map);
  return map;
}

/**
 * Remove a conversation from the active-summary registry (read/opened/replied)
 * and return the remaining map so the caller can refresh or cancel the summary.
 */
function removeActiveConversation(conversationId: string): ActiveConversationMap {
  const map = readActiveConversations();
  if (map[conversationId]) {
    delete map[conversationId];
    writeActiveConversations(map);
  }
  return map;
}

// Notifee VALIDATES `vibrationPattern`: it MUST have an EVEN number of entries
// (alternating wait/buzz durations) and createChannel()/displayNotification()
// THROW on a malformed (odd-length) pattern. A throw inside createMessageChannel
// means the messages channel is NEVER created, and Android then SILENTLY DROPS
// every message notification (sound may play, but no status-bar/lock-screen
// entry) — the root cause of "message push not appearing while calls work".
// This guard returns the pattern only when it is safe, else undefined so the
// caller omits the override entirely (never passes a bad pattern to Notifee).
function safeVibrationPattern(pattern: number[]): number[] | undefined {
  if (!Array.isArray(pattern) || pattern.length === 0) return undefined;
  if (pattern.length % 2 !== 0) return undefined;
  if (
    pattern.some((v) => typeof v !== "number" || !Number.isFinite(v) || v < 0)
  ) {
    return undefined;
  }
  return pattern;
}

// Even-length message vibration pattern (wait 0, buzz 160, pause 80, buzz 160).
// Mirrors the expo-notifications "messages" channel cadence. MUST stay
// even-length (see safeVibrationPattern) or the messages channel won't create.
const MESSAGE_VIBRATION_PATTERN = [0, 160, 80, 160];

